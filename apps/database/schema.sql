-- Esquema de referencia del dominio de Chaos.
--
-- La fuente de verdad para cambios estructurales
-- son las migraciones de Alembic ubicadas en:
--
-- apps/api/migrations/
--
-- No aplicar manualmente este archivo en Supabase
-- cuando exista una migración Alembic equivalente.

CREATE TABLE public.players (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    auth_user_id BIGINT NOT NULL UNIQUE,

    user_name TEXT,
    bio TEXT,
    country_code CHAR(2),
    timezone TEXT,
    avatar_url TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_players_auth_user
        FOREIGN KEY (auth_user_id)
        REFERENCES public.app_users(id)
        ON DELETE CASCADE
);


CREATE TABLE public.steam_profiles (
    player_id UUID PRIMARY KEY,

    steamid BIGINT NOT NULL UNIQUE,

    persona_name TEXT,
    profile_url TEXT,
    avatar_url TEXT,

    community_visibility SMALLINT,
    steam_country_code CHAR(2),

    account_created_at TIMESTAMPTZ,
    last_synced_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_steam_profiles_player_id_players
        FOREIGN KEY (player_id)
        REFERENCES public.players(id)
        ON DELETE CASCADE
);


CREATE TABLE public.languages (
    code TEXT PRIMARY KEY,
    name TEXT NOT NULL
);


CREATE TABLE public.player_languages (
    player_id UUID NOT NULL,
    language_code TEXT NOT NULL,
    level TEXT,

    PRIMARY KEY (
        player_id,
        language_code
    ),

    CONSTRAINT fk_player_languages_player_id_players
        FOREIGN KEY (player_id)
        REFERENCES public.players(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_player_languages_language_code_languages
        FOREIGN KEY (language_code)
        REFERENCES public.languages(code)
        ON DELETE CASCADE
);


CREATE TABLE public.player_availability (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

    player_id UUID NOT NULL,

    day_of_week SMALLINT NOT NULL,

    start_time TIME NOT NULL,
    end_time TIME NOT NULL,

    CONSTRAINT fk_player_availability_player_id_players
        FOREIGN KEY (player_id)
        REFERENCES public.players(id)
        ON DELETE CASCADE
);


CREATE TABLE public.interests (
    id INTEGER
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    name TEXT NOT NULL,
    category TEXT NOT NULL
);


CREATE TABLE public.player_interests (
    player_id UUID NOT NULL,
    interest_id INTEGER NOT NULL,

    PRIMARY KEY (
        player_id,
        interest_id
    ),

    CONSTRAINT fk_player_interests_player_id_players
        FOREIGN KEY (player_id)
        REFERENCES public.players(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_player_interests_interest_id_interests
        FOREIGN KEY (interest_id)
        REFERENCES public.interests(id)
        ON DELETE CASCADE
);


CREATE TABLE public.apps (
    appid INTEGER PRIMARY KEY,

    name TEXT NOT NULL,
    icon_url TEXT,
    header_image_url TEXT,
    short_description TEXT,

    developers TEXT[],
    publishers TEXT[],

    release_date DATE,
    is_free BOOLEAN,

    platform_windows BOOLEAN,
    platform_mac BOOLEAN,
    platform_linux BOOLEAN,

    is_multiplayer BOOLEAN,
    is_coop BOOLEAN,
    is_pvp BOOLEAN,

    achievements_total SMALLINT,

    percent_positive SMALLINT,
    total_reviews INTEGER,
    review_label TEXT,

    median_playtime_min INTEGER,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);



CREATE TABLE public.player_games (
    player_id UUID NOT NULL,
    appid INTEGER NOT NULL,

    favorite BOOLEAN NOT NULL DEFAULT FALSE,

    playtime_forever_min INTEGER,
    playtime_2weeks_min INTEGER,

    playtime_windows_min INTEGER,
    playtime_mac_min INTEGER,
    playtime_linux_min INTEGER,
    playtime_deck_min INTEGER,

    last_played_at TIMESTAMPTZ,
    first_seen_on DATE,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (player_id, appid),

    CONSTRAINT fk_player_games_player
        FOREIGN KEY (player_id)
        REFERENCES public.players(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_player_games_app
        FOREIGN KEY (appid)
        REFERENCES public.apps(appid)
        ON DELETE CASCADE
);